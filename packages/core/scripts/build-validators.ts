import entitySchema from '@prodid/spec/schemas/org.prodid.entity.json'
import feedSchema from '@prodid/spec/schemas/org.prodid.feed.json'
import itemSchema from '@prodid/spec/schemas/org.prodid.item.json'
import sourceSchema from '@prodid/spec/schemas/org.prodid.source.json'
import { _ } from 'ajv'
import addFormats from 'ajv-formats'
import Ajv2020 from 'ajv/dist/2020'
import standaloneCode from 'ajv/dist/standalone'

const OUT = new URL('../src/record/validators.generated.js', import.meta.url)
const OUT_TYPES = new URL('../src/record/validators.generated.d.ts', import.meta.url)
const BANNER = '// Generated by scripts/build-validators.ts from @prodid/spec schemas. Do not edit.'

const ajv = new Ajv2020({
	allErrors: true,
	strict: true,
	code: {
		source: true,
		esm: true,
		lines: true,
		formats: _`require("ajv-formats/dist/formats").fullFormats`,
	},
})

addFormats(ajv, ['uri', 'email', 'date-time'])
ajv.addSchema(itemSchema)
ajv.addSchema(feedSchema)
ajv.addSchema(entitySchema)
ajv.addSchema(sourceSchema)

const source = toEsm(
	standaloneCode(ajv, { item: itemSchema.$id, feed: feedSchema.$id, entity: entitySchema.$id, source: sourceSchema.$id }),
)

if (/\brequire\s*\(/.test(source)) throw new Error('generated validators still contain require()')
if (/\beval\s*\(|\bFunction\s*\(/.test(source)) throw new Error('generated validators contain eval or Function')

await Bun.write(OUT, `${BANNER}\n${source.trimEnd()}\n`)
await Bun.write(OUT_TYPES, declarations())

// Ajv emits CommonJS `require()` for its runtime helpers and for the format table even under
// `code.esm`, which no ES module can evaluate. Hoist each one into a static import instead.
function toEsm(code: string): string {
	const imports = new Map<string, string>()
	const body = code.replace(/require\("([^"]+)"\)(\.default\b)?/g, (_match: string, specifier: string, asDefault?: string) => {
		const key = `${specifier}\u0000${asDefault ? 'default' : 'namespace'}`
		const existing = imports.get(key)
		if (existing !== undefined) return existing
		const name = `dep${imports.size}`
		imports.set(key, name)
		return name
	})
	// These helpers are CommonJS with `exports.default`. Bun honours `__esModule` on a default
	// import; esbuild (wrangler) does not inside a `"type": "module"` package and hands back the
	// whole exports object, so unwrap it here.
	const lines = [...imports].map(([key, name]) => {
		const [specifier, kind] = key.split('\u0000')
		return kind === 'default'
			? `import ${name}_module from '${specifier}'\nconst ${name} = ${name}_module.__esModule ? ${name}_module.default : ${name}_module`
			: `import * as ${name} from '${specifier}'`
	})
	return `${lines.join('\n')}\n${body.replace(/^"use strict";\n?/, '')}`
}

function declarations(): string {
	return `${BANNER}
import type { EntityRecord, FeedRecord, ItemRecord, SourceRecord } from './types'

export interface SchemaError {
	instancePath: string
	schemaPath: string
	keyword: string
	params: Record<string, unknown>
	message?: string
}

export interface SchemaValidator<T> {
	(data: unknown): data is T
	errors?: SchemaError[] | null | undefined
}

export declare const item: SchemaValidator<ItemRecord>
export declare const feed: SchemaValidator<FeedRecord>
export declare const entity: SchemaValidator<EntityRecord>
export declare const source: SchemaValidator<SourceRecord>
`
}
